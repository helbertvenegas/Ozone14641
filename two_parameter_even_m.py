"""Independent Smith-normal-form certificate for the *even m* subcase.

This is a conditional consequence of the monomial manuscript's
Theorem B, Propositions MNP/OWZ and Table tab:split, not an independent
proof of those inputs or of the center.
"""
from sympy import ZZ, Matrix
from sympy.matrices.normalforms import smith_normal_form

FAMILIES = ('M', 'N', 'O', 'P', 'W', 'Z')

def invariant_factors(m, mp, family):
    if family not in FAMILIES:
        raise ValueError('not a two-parameter monomial family')
    if not isinstance(m, int) or m <= 0 or m % 2:
        raise ValueError('even m > 0 required')
    if not isinstance(mp, int) or mp <= 0:
        raise ValueError('mprime > 0 required')
    # Table tab:split: r^m, rho^m both have degree m*delta
    # and tildeX^mp, tildeY^mp have degrees 2mp*alpha,2mp*beta.
    # For even m, 2delta=0 already implies m*delta=0.
    # Gamma / Gamma_K is generated by alpha,beta,delta.
    R = Matrix([[2*mp,0,0],[0,2*mp,0],[0,0,2]])
    D = smith_normal_form(R, domain=ZZ)
    factors = tuple(sorted(abs(int(D[i,i])) for i in range(3)))
    assert factors == (2,2*mp,2*mp)
    return {'family':family, 'm':m, 'mprime':mp,
            'invariant_factors':factors,'order':2*(2*mp)**2,
            'scope':'conditional on monomial manuscript Theorem B, tab:split and props MNP/OWZ'}

if __name__=='__main__':
    for family in FAMILIES:
        for m in (2,4,6,8,10):
            for mp in (1,2,3,4,5,8):
                d=invariant_factors(m,mp,family)
                assert d['order']==8*mp*mp
    print('PASS: 180 exact SNF cases; symbolic argument in EVEN_M_THEOREM.tex')
